 * Material Symbols не используются: они узнаются мгновенно и выдают
 * андроидное происхождение интерфейса. Phosphor по геометрии и весам
 * ближе всего к SF Symbols.
 *
 * Файл сгенерирован из официальных SVG phosphor-icons 2.1.1 (MIT):
 * контуры взяты как есть, поэтому пропорции совпадают с оригиналом.
 * Холст 256x256 — родной размер Phosphor, отображается в 24dp.
 * Иконки создаются лениво: разбор контура стоит денег, а на одном
 * экране используется хорошо если десяток.
 */
private const val VIEWPORT = 256f

private fun phosphor(name: String, vararg pathData: String): ImageVector =
    ImageVector.Builder(
        name = name,
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = VIEWPORT,
        viewportHeight = VIEWPORT
    ).apply {
        pathData.forEach { data ->
            addPath(
                pathData = PathParser().parsePathString(data).toNodes(),
                fill = SolidColor(Color.Black)
            )
        }
    }.build()

